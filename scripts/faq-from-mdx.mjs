// Keep the docs FAQPage schemas identical to the visible pages, in every
// language.
//
// Google requires structured data to match what the reader sees. For months
// src/lib/faq-data.ts was a hand-kept copy of content/docs/faq.mdx, and the
// two drifted apart in nine answers without anything noticing. This script
// derives the schema from the page instead of trusting anyone to mirror it.
//
// It reads two FAQs per language, from each locale's own MDX:
//   content/docs/faq[.<loc>].mdx          every `## ` heading is a question
//   content/docs/claude-code[.<loc>].mdx  the `### ` headings of the last
//                                         `## ` section (the page's FAQ)
// Until 13 Oct the data was English only, so translated FAQ pages carried no
// FAQPage at all. A new language needs no code here: its `.<loc>.mdx` twin is
// picked up by the file name.
//
//   node scripts/faq-from-mdx.mjs          rewrite src/lib/faq-data.ts
//   node scripts/faq-from-mdx.mjs --check  fail if it is out of date (CI)
//
// No dependencies: node builtins only, so the guard can run it before npm ci.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';

const DIR = 'content/docs';
const OUT = 'src/lib/faq-data.ts';

// Markdown to the text a reader sees: link text without the URL, no emphasis
// markers, no code backticks, no blockquote markers, no `[#id]` anchor.
function visibleText(md) {
  return md
    .replace(/\s*\[#[^\]\s]+\]\s*$/gm, '')
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/^>\s?/gm, '')
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .join(' ');
}

function body(mdx) {
  return mdx.replace(/^---[\s\S]*?\n---\n/, '').replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
}

function entries(sections) {
  return sections.map((s) => {
    const nl = s.indexOf('\n');
    return { question: visibleText(s.slice(0, nl)), answer: visibleText(s.slice(nl + 1)) };
  });
}

// /docs/faq: every H2 is a question.
export function faqEntries(mdx) {
  return entries(body(mdx).split(/^## /m).slice(1));
}

// /docs/claude-code: the H3 questions under the last H2 that has any.
function claudeCodeEntries(mdx) {
  const h2 = body(mdx).split(/^## /m).slice(1).filter((s) => /^### /m.test(s));
  if (!h2.length) throw new Error('claude-code: no `### ` FAQ section');
  return entries(h2.at(-1).split(/^### /m).slice(1));
}

// en first, then every translated twin in alphabetical order.
function byLocale(name, parse) {
  const locs = readdirSync(DIR)
    .map((f) => f.match(new RegExp(`^${name}\\.([a-z]{2})\\.mdx$`))?.[1])
    .filter(Boolean)
    .sort();
  const out = { en: parse(readFileSync(`${DIR}/${name}.mdx`, 'utf8')) };
  for (const l of locs) out[l] = parse(readFileSync(`${DIR}/${name}.${l}.mdx`, 'utf8'));
  const n = out.en.length;
  for (const [l, e] of Object.entries(out)) {
    if (e.length !== n) console.warn(`note: ${name}.${l} has ${e.length} questions, en has ${n}`);
  }
  return out;
}

function renderMap(name, map) {
  const locs = Object.entries(map)
    .map(([l, list]) => {
      const items = list
        .map(
          (e) =>
            `    {\n      question: ${JSON.stringify(e.question)},\n      answer:\n        ${JSON.stringify(e.answer)},\n    },`,
        )
        .join('\n');
      return `  ${l}: [\n${items}\n  ],`;
    })
    .join('\n');
  return `export const ${name}: Record<string, FaqEntry[]> = {\n${locs}\n};\n`;
}

function render() {
  return `// GENERATED by scripts/faq-from-mdx.mjs from content/docs/faq*.mdx and
// content/docs/claude-code*.mdx. Do not edit by hand: edit the page, then run
// \`node scripts/faq-from-mdx.mjs\`. The FAQPage JSON-LD must match the
// visible page word for word, and the guard fails the build when it does not.
export type FaqEntry = { question: string; answer: string };

${renderMap('FAQ_BY_LOCALE', byLocale('faq', faqEntries))}
${renderMap('CLAUDE_CODE_FAQ_BY_LOCALE', byLocale('claude-code', claudeCodeEntries))}`;
}

const expected = render();

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== expected) {
    console.error(`FAIL: ${OUT} does not match the FAQ pages. Run: node scripts/faq-from-mdx.mjs`);
    process.exit(1);
  }
  console.log(`OK: FAQPage schemas match the visible FAQs`);
} else {
  writeFileSync(OUT, expected);
  console.log(`wrote ${OUT}`);
}
