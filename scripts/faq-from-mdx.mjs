// Keep the /docs/faq FAQPage schema identical to the visible page.
//
// Google requires structured data to match what the reader sees. For months
// src/lib/faq-data.ts was a hand-kept copy of content/docs/faq.mdx, and the
// two drifted apart in nine answers without anything noticing. This script
// derives the schema from the page instead of trusting anyone to mirror it.
//
//   node scripts/faq-from-mdx.mjs          rewrite src/lib/faq-data.ts
//   node scripts/faq-from-mdx.mjs --check  fail if it is out of date (CI)
//
// No dependencies: node builtins only, so the guard can run it before npm ci.
import { readFileSync, writeFileSync } from 'node:fs';

const MDX = 'content/docs/faq.mdx';
const OUT = 'src/lib/faq-data.ts';

// Markdown to the text a reader sees: link text without the URL, no emphasis
// markers, no code backticks, no blockquote markers.
function visibleText(md) {
  return md
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1')
    .replace(/`([^`]+)`/g, '$1')
    .replace(/^>\s?/gm, '')
    .split(/\n\s*\n/)
    .map((p) => p.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
    .join(' ');
}

export function faqEntries(mdx) {
  const body = mdx
    .replace(/^---[\s\S]*?\n---\n/, '')
    .replace(/\{\/\*[\s\S]*?\*\/\}/g, '');
  const sections = body.split(/^## /m).slice(1);
  return sections.map((s) => {
    const nl = s.indexOf('\n');
    return {
      question: visibleText(s.slice(0, nl)),
      answer: visibleText(s.slice(nl + 1)),
    };
  });
}

function render(entries) {
  const lines = entries
    .map(
      (e) =>
        `  {\n    question: ${JSON.stringify(e.question)},\n    answer:\n      ${JSON.stringify(e.answer)},\n  },`,
    )
    .join('\n');
  return `// GENERATED by scripts/faq-from-mdx.mjs from content/docs/faq.mdx. Do not
// edit by hand: edit the page, then run \`node scripts/faq-from-mdx.mjs\`.
// The FAQPage JSON-LD must match the visible page word for word, and the
// guard fails the build when it does not.
export type FaqEntry = { question: string; answer: string };

export const FAQ_ENTRIES: FaqEntry[] = [
${lines}
];
`;
}

const expected = render(faqEntries(readFileSync(MDX, 'utf8')));

if (process.argv.includes('--check')) {
  if (readFileSync(OUT, 'utf8') !== expected) {
    console.error(
      `FAIL: ${OUT} does not match ${MDX}. Run: node scripts/faq-from-mdx.mjs`,
    );
    process.exit(1);
  }
  console.log(`OK: FAQPage schema matches the visible FAQ`);
} else {
  writeFileSync(OUT, expected);
  console.log(`wrote ${OUT}`);
}
